-- =========================================================================
-- HỆ THỐNG CƠ SỞ DỮ LIỆU FAMILYCONNECT (POSTGRESQL)
-- =========================================================================

-- 1. BẢNG NGƯỜI DÙNG & XÁC THỰC (USERS & SECURITY)
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(30) DEFAULT 'MEMBER', -- 'ADMIN', 'MODERATOR', 'MEMBER'
    avatar_url TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. BẢNG GIA TỘC (FAMILIES)
CREATE TABLE IF NOT EXISTS families (
    family_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. BẢNG CHI / NHÁNH DÒNG HỌ (FAMILY BRANCHES)
CREATE TABLE IF NOT EXISTS family_branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    description TEXT
);

-- 4. BẢNG THÀNH VIÊN GIA PHẢ (MEMBERS)
CREATE TABLE IF NOT EXISTS members (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    branch_id BIGINT REFERENCES family_branches(branch_id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    full_name VARCHAR(150) NOT NULL,
    gender VARCHAR(20) CHECK (gender IN ('male', 'female', 'other')),
    generation INT NOT NULL DEFAULT 1,
    birth_date DATE,
    death_date DATE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. BẢNG QUAN HỆ CHA/MẸ - CON (PARENT-CHILD RELATIONSHIPS)
CREATE TABLE IF NOT EXISTS parent_child_relationships (
    relationship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL REFERENCES members(member_id) ON DELETE CASCADE,
    child_id BIGINT NOT NULL REFERENCES members(member_id) ON DELETE CASCADE,
    relationship_type VARCHAR(30) NOT NULL DEFAULT 'father',
    CONSTRAINT uq_parent_child UNIQUE (parent_id, child_id),
    CONSTRAINT chk_not_self_parent CHECK (parent_id <> child_id)
);

-- 6. BẢNG QUAN HỆ HÔN NHÂN (MARRIAGES)
CREATE TABLE IF NOT EXISTS marriages (
    marriage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner1_id BIGINT NOT NULL REFERENCES members(member_id) ON DELETE CASCADE,
    partner2_id BIGINT NOT NULL REFERENCES members(member_id) ON DELETE CASCADE,
    start_date DATE,
    end_date DATE,
    status VARCHAR(30) DEFAULT 'MARRIED',
    CONSTRAINT chk_different_partners CHECK (partner1_id <> partner2_id)
);

-- 7. BẢNG HỒ SƠ MỞ RỘNG (MEMBER PROFILES)
CREATE TABLE IF NOT EXISTS member_profiles (
    member_id BIGINT PRIMARY KEY REFERENCES members(member_id) ON DELETE CASCADE,
    occupation VARCHAR(150),
    education VARCHAR(150),
    biography TEXT
);

-- 8. BẢNG TÀI LIỆU DI SẢN (FAMILY DOCUMENTS)
CREATE TABLE IF NOT EXISTS family_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    member_id BIGINT REFERENCES members(member_id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL,
    document_type VARCHAR(50),
    file_url TEXT,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. BẢNG VAI TRÒ GIA ĐÌNH (ROLES)
CREATE TABLE IF NOT EXISTS roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,
    description TEXT
);

-- 10. BẢNG LIÊN KẾT THÀNH VIÊN GIA ĐÌNH & PHÂN QUYỀN (FAMILY MEMBERS)
CREATE TABLE IF NOT EXISTS family_members (
    family_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    status VARCHAR(20) DEFAULT 'APPROVED', -- 'PENDING', 'APPROVED', 'REJECTED'
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_family UNIQUE (user_id, family_id)
);

-- 11. BẢNG BÀI VIẾT & THÔNG BÁO CỘNG ĐỒNG (POSTS)
CREATE TABLE IF NOT EXISTS posts (
    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    is_announcement BOOLEAN DEFAULT FALSE,
    status VARCHAR(20) DEFAULT 'ACTIVE', -- 'ACTIVE', 'HIDDEN', 'FLAGGED'
    media_urls TEXT[], 
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 12. BẢNG BÌNH LUẬN (POST COMMENTS)
CREATE TABLE IF NOT EXISTS post_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(post_id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 13. BẢNG THẢ CẢM XÚC (POST REACTIONS)
CREATE TABLE IF NOT EXISTS post_reactions (
    reaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(post_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reaction_type VARCHAR(20) DEFAULT 'LIKE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_post_user_reaction UNIQUE (post_id, user_id)
);

-- 14. BẢNG SỰ KIỆN GIA TỘC (EVENTS)
CREATE TABLE IF NOT EXISTS events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES families(family_id) ON DELETE CASCADE,
    creator_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    event_date TIMESTAMP NOT NULL,
    location VARCHAR(255),
    media_urls TEXT[],
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 15. BẢNG ĐIỂM DANH SỰ KIỆN (EVENT RSVPs)
CREATE TABLE IF NOT EXISTS event_rsvps (
    rsvp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(event_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    status VARCHAR(20) DEFAULT 'GOING', -- 'GOING', 'DECLINED', 'TENTATIVE'
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_event_user_rsvp UNIQUE (event_id, user_id)
);

-- 16. BẢNG LỊCH SỬ CHAT AI (AI CHAT HISTORIES)
CREATE TABLE IF NOT EXISTS ai_chat_histories (
    chat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    family_id BIGINT REFERENCES families(family_id) ON DELETE CASCADE,
    conversation_id VARCHAR(100) NOT NULL,
    prompt TEXT NOT NULL,
    response TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 17. BẢNG NHẬT KÝ KIỂM TOÁN HỆ THỐNG (AUDIT LOGS)
CREATE TABLE IF NOT EXISTS audit_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    action VARCHAR(50) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id VARCHAR(50),
    details TEXT,
    ip_address VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

